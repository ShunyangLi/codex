def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--directory", type=Path, required=True)
    add_decision_arguments(parser)
    args = parser.parse_args()
    store = RunStore(args.directory, "jev-cases")
    judge = JevDecisionMaker(ExecutionProfile(**decision_settings(args)), store, lambda: 120)
    results = []
    for name, kind, expected, payload in CASES:
        decision = judge(kind, name, payload)
        row = {
            "case": name,
            "kind": kind,
            "expected": expected,
            "score": decision.score,
            "accepted": decision.accepted,
            "matches": decision.accepted == expected,
            "decision_id": decision.id,
            "prompt_version": decision.prompt_version,
        }
        results.append(row)
        print(json.dumps(row), flush=True)
    print("results: " + store.write_json(f"results/{digest(results)}.json", results), flush=True)
    if not all(row["matches"] for row in results):
        raise SystemExit(1)


if __name__ == "__main__":
    main()
